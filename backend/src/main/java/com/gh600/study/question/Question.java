package com.gh600.study.question;

import java.util.ArrayList;
import java.util.List;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;

/**
 * JPA Entity representing one GH-600 practice question.
 *
 * @Entity tells Hibernate to map this class to a database table ("question").
 * With spring.jpa.hibernate.ddl-auto=update, Hibernate inspects the fields below
 * and automatically runs CREATE TABLE / ALTER TABLE on startup.
 */
@Entity
public class Question {

    /**
     * Primary key, auto-incremented by H2 (GENERATED BY DEFAULT AS IDENTITY).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The question prompt. Default VARCHAR length in JPA is 255, which is too short
     * for scenario-based exam questions, so we widen it to 2000.
     */
    @Column(nullable = false, length = 2000)
    private String text;

    /**
     * EnumType.STRING stores "AGENT_ARCHITECTURE_AND_SDLC" instead of 0.
     * Note: JPA's default is EnumType.ORDINAL, which breaks existing data if enum order changes.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 60)
    private Domain domain;

    /**
     * Overall explanation shown after the learner answers the question.
     */
    @Column(nullable = false, length = 2000)
    private String explanation;

    /**
     * True when the question requires selecting more than one option ("Select all that apply").
     */
    @Column(nullable = false)
    private boolean multiSelect;

    /**
     * One Question has many AnswerOptions.
     *
     * - mappedBy = "question": tells JPA that AnswerOption.question owns the foreign key
     *   column (question_id). Without mappedBy, JPA would create an extra join table.
     * - cascade = CascadeType.ALL: saving or deleting a Question automatically saves or
     *   deletes its AnswerOptions.
     * - orphanRemoval = true: removing an AnswerOption from this list deletes its row in the DB.
     * - Fetch type for @OneToMany is LAZY by default: options are only loaded when accessed
     *   (or when fetched eagerly via JOIN FETCH).
     */
    @OneToMany(mappedBy = "question", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("id ASC")
    private List<AnswerOption> options = new ArrayList<>();

    /**
     * JPA requires a no-arg constructor (at least protected) so Hibernate can instantiate
     * the class via reflection when reading rows from the database.
     */
    protected Question() {
    }

    public Question(String text, Domain domain, String explanation, boolean multiSelect) {
        this.text = text;
        this.domain = domain;
        this.explanation = explanation;
        this.multiSelect = multiSelect;
    }

    /**
     * Helper method that keeps BOTH sides of the bidirectional relationship in sync.
     * Because AnswerOption.question is the owning side (it holds the foreign key),
     * forgetting option.setQuestion(this) would leave question_id NULL in the database!
     */
    public Question addOption(AnswerOption option) {
        options.add(option);
        option.setQuestion(this);
        return this;
    }

    public void removeOption(AnswerOption option) {
        options.remove(option);
        option.setQuestion(null);
    }

    public Long getId() {
        return id;
    }

    public String getText() {
        return text;
    }

    public void setText(String text) {
        this.text = text;
    }

    public Domain getDomain() {
        return domain;
    }

    public void setDomain(Domain domain) {
        this.domain = domain;
    }

    public String getExplanation() {
        return explanation;
    }

    public void setExplanation(String explanation) {
        this.explanation = explanation;
    }

    public boolean isMultiSelect() {
        return multiSelect;
    }

    public void setMultiSelect(boolean multiSelect) {
        this.multiSelect = multiSelect;
    }

    public List<AnswerOption> getOptions() {
        return options;
    }
}

